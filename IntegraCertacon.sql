CREATE DATABASE IntegraCertacon

USE IntegraCertacon;
GO

CREATE TABLE dbo.USUARIO
(
    Usuario_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_USUARIO_Id DEFAULT NEWID(),
    Nome NVARCHAR(150) NOT NULL,
    Email NVARCHAR(256) NOT NULL,
    SenhaHash NVARCHAR(500) NOT NULL,
    Ativo BIT NOT NULL CONSTRAINT DF_USUARIO_Ativo DEFAULT 1,
    RazaoSocial NVARCHAR(200) NULL,
    CNPJ NVARCHAR(14) NULL,
    TelefoneContato NVARCHAR(30) NULL,
    DataCriacao DATETIME2 NOT NULL CONSTRAINT DF_USUARIO_DataCriacao DEFAULT SYSDATETIME(),
    CONSTRAINT PK_USUARIO PRIMARY KEY (Usuario_Id),
    CONSTRAINT UQ_USUARIO_Email UNIQUE (Email),
    CONSTRAINT CK_USUARIO_CNPJ CHECK (CNPJ IS NULL OR LEN(CNPJ) = 14)
);
GO

CREATE TABLE dbo.PERFIL
(
    Perfil_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_PERFIL_Id DEFAULT NEWID(),
    Nome NVARCHAR(100) NOT NULL,
    Descricao NVARCHAR(300) NULL,
    Ativo BIT NOT NULL CONSTRAINT DF_PERFIL_Ativo DEFAULT 1,
    DataCriacao DATETIME2 NOT NULL CONSTRAINT DF_PERFIL_DataCriacao DEFAULT SYSDATETIME(),
    CONSTRAINT PK_PERFIL PRIMARY KEY (Perfil_Id),
    CONSTRAINT UQ_PERFIL_Nome UNIQUE (Nome)
);
GO

CREATE TABLE dbo.USUARIO_PERFIL
(
    UsuarioPerfil_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_USUARIO_PERFIL_Id DEFAULT NEWID(),
    Usuario_Id UNIQUEIDENTIFIER NOT NULL,
    Perfil_Id UNIQUEIDENTIFIER NOT NULL,
    DataAtribuicao DATETIME2 NOT NULL CONSTRAINT DF_USUARIO_PERFIL_Data DEFAULT SYSDATETIME(),
    CONSTRAINT PK_USUARIO_PERFIL PRIMARY KEY (UsuarioPerfil_Id),
    CONSTRAINT FK_USUARIO_PERFIL_USUARIO FOREIGN KEY (Usuario_Id) REFERENCES dbo.USUARIO(Usuario_Id),
    CONSTRAINT FK_USUARIO_PERFIL_PERFIL FOREIGN KEY (Perfil_Id) REFERENCES dbo.PERFIL(Perfil_Id),
    CONSTRAINT UQ_USUARIO_PERFIL UNIQUE (Usuario_Id, Perfil_Id)
);
GO

CREATE TABLE dbo.TEMA
(
    Tema_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_TEMA_Id DEFAULT NEWID(),
    Nome NVARCHAR(150) NOT NULL,
    Descricao NVARCHAR(400) NULL,
    Ativo BIT NOT NULL CONSTRAINT DF_TEMA_Ativo DEFAULT 1,
    DataCriacao DATETIME2 NOT NULL CONSTRAINT DF_TEMA_DataCriacao DEFAULT SYSDATETIME(),
    DataAtualizacao DATETIME2 NULL,
    CONSTRAINT PK_TEMA PRIMARY KEY (Tema_Id),
    CONSTRAINT UQ_TEMA_Nome UNIQUE (Nome)
);
GO

CREATE TABLE dbo.ARTIGO
(
    Artigo_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ARTIGO_Id DEFAULT NEWID(),
    Tema_Id UNIQUEIDENTIFIER NOT NULL,
    AutorUsuario_Id UNIQUEIDENTIFIER NOT NULL,
    Titulo NVARCHAR(200) NOT NULL,
    Resumo NVARCHAR(500) NULL,
    Conteudo NVARCHAR(MAX) NOT NULL,
    Visibilidade NVARCHAR(20) NOT NULL CONSTRAINT DF_ARTIGO_Visibilidade DEFAULT 'PUBLICO',
    Status NVARCHAR(30) NOT NULL CONSTRAINT DF_ARTIGO_Status DEFAULT 'RASCUNHO',
    DataCriacao DATETIME2 NOT NULL CONSTRAINT DF_ARTIGO_DataCriacao DEFAULT SYSDATETIME(),
    DataAtualizacao DATETIME2 NULL,
    DataPublicacao DATETIME2 NULL,
    CONSTRAINT PK_ARTIGO PRIMARY KEY (Artigo_Id),
    CONSTRAINT FK_ARTIGO_TEMA FOREIGN KEY (Tema_Id) REFERENCES dbo.TEMA(Tema_Id),
    CONSTRAINT FK_ARTIGO_USUARIO FOREIGN KEY (AutorUsuario_Id) REFERENCES dbo.USUARIO(Usuario_Id),
    CONSTRAINT CK_ARTIGO_Visibilidade CHECK (Visibilidade IN ('PUBLICO', 'EXCLUSIVO')),
    CONSTRAINT CK_ARTIGO_Status CHECK (Status IN ('RASCUNHO', 'EM_REVISAO', 'APROVADO', 'REJEITADO', 'PUBLICADO', 'ARQUIVADO'))
);
GO

CREATE TABLE dbo.REVISAO_ARTIGO
(
    RevisaoArtigo_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_REVISAO_ARTIGO_Id DEFAULT NEWID(),
    Artigo_Id UNIQUEIDENTIFIER NOT NULL,
    Usuario_Id UNIQUEIDENTIFIER NOT NULL,
    Status NVARCHAR(30) NOT NULL,
    Comentario NVARCHAR(MAX) NULL,
    StatusAnterior NVARCHAR(30) NULL,
    StatusNovo NVARCHAR(30) NOT NULL,
    DataRevisao DATETIME2 NOT NULL CONSTRAINT DF_REVISAO_ARTIGO_Data DEFAULT SYSDATETIME(),
    CONSTRAINT PK_REVISAO_ARTIGO PRIMARY KEY (RevisaoArtigo_Id),
    CONSTRAINT FK_REVISAO_ARTIGO_ARTIGO FOREIGN KEY (Artigo_Id) REFERENCES dbo.ARTIGO(Artigo_Id),
    CONSTRAINT FK_REVISAO_ARTIGO_USUARIO FOREIGN KEY (Usuario_Id) REFERENCES dbo.USUARIO(Usuario_Id),
    CONSTRAINT CK_REVISAO_ARTIGO_Status CHECK (Status IN ('APROVADA', 'REJEITADA', 'AJUSTES_SOLICITADOS')),
    CONSTRAINT CK_REVISAO_ARTIGO_StatusNovo CHECK (StatusNovo IN ('RASCUNHO', 'EM_REVISAO', 'APROVADO', 'REJEITADO', 'PUBLICADO', 'ARQUIVADO'))
);
GO

CREATE TABLE dbo.NOTA_FISCAL
(
    NotaFiscal_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_NOTA_FISCAL_Id DEFAULT NEWID(),
    Usuario_Id UNIQUEIDENTIFIER NOT NULL,
    Numero NVARCHAR(30) NOT NULL,
    Serie NVARCHAR(10) NULL,
    ChaveAcesso NVARCHAR(44) NULL,
    CNPJEmitente NVARCHAR(14) NULL,
    CNPJDestinatario NVARCHAR(14) NULL,
    DataEmissao DATETIME2 NULL,
    ValorTotal DECIMAL(18,2) NOT NULL CONSTRAINT DF_NOTA_FISCAL_Valor DEFAULT 0,
    Status NVARCHAR(30) NOT NULL CONSTRAINT DF_NOTA_FISCAL_Status DEFAULT 'IMPORTADA',
    CaminhoArquivo NVARCHAR(500) NULL,
    DataEnvio DATETIME2 NOT NULL CONSTRAINT DF_NOTA_FISCAL_DataEnvio DEFAULT SYSDATETIME(),
    CONSTRAINT PK_NOTA_FISCAL PRIMARY KEY (NotaFiscal_Id),
    CONSTRAINT FK_NOTA_FISCAL_USUARIO FOREIGN KEY (Usuario_Id) REFERENCES dbo.USUARIO(Usuario_Id),
    CONSTRAINT UQ_NOTA_FISCAL_ChaveAcesso UNIQUE (ChaveAcesso),
    CONSTRAINT CK_NOTA_FISCAL_Status CHECK (Status IN ('IMPORTADA', 'VALIDADA', 'REJEITADA')),
    CONSTRAINT CK_NOTA_FISCAL_Valor CHECK (ValorTotal >= 0),
    CONSTRAINT CK_NOTA_FISCAL_CNPJEmitente CHECK (CNPJEmitente IS NULL OR LEN(CNPJEmitente) = 14),
    CONSTRAINT CK_NOTA_FISCAL_CNPJDestinatario CHECK (CNPJDestinatario IS NULL OR LEN(CNPJDestinatario) = 14)
);
GO

CREATE TABLE dbo.ITEM_NOTA_FISCAL
(
    ItemNotaFiscal_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_ITEM_NOTA_FISCAL_Id DEFAULT NEWID(),
    NotaFiscal_Id UNIQUEIDENTIFIER NOT NULL,
    NumeroItem INT NOT NULL,
    CodigoProduto NVARCHAR(60) NULL,
    Descricao NVARCHAR(300) NOT NULL,
    NCM NVARCHAR(10) NULL,
    CFOP NVARCHAR(10) NULL,
    Quantidade DECIMAL(18,4) NOT NULL,
    ValorUnitario DECIMAL(18,4) NOT NULL,
    ValorTotal DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_ITEM_NOTA_FISCAL PRIMARY KEY (ItemNotaFiscal_Id),
    CONSTRAINT FK_ITEM_NOTA_FISCAL_NOTA_FISCAL FOREIGN KEY (NotaFiscal_Id) REFERENCES dbo.NOTA_FISCAL(NotaFiscal_Id),
    CONSTRAINT UQ_ITEM_NOTA_FISCAL UNIQUE (NotaFiscal_Id, NumeroItem),
    CONSTRAINT CK_ITEM_NOTA_FISCAL_Quantidade CHECK (Quantidade > 0),
    CONSTRAINT CK_ITEM_NOTA_FISCAL_ValorUnitario CHECK (ValorUnitario >= 0),
    CONSTRAINT CK_ITEM_NOTA_FISCAL_ValorTotal CHECK (ValorTotal >= 0)
);
GO

CREATE TABLE dbo.LOG_AUDITORIA
(
    LogAuditoria_Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_LOG_AUDITORIA_Id DEFAULT NEWID(),
    Usuario_Id UNIQUEIDENTIFIER NULL,
    Acao NVARCHAR(100) NOT NULL,
    TabelaAfetada NVARCHAR(100) NULL,
    Registro_Id UNIQUEIDENTIFIER NULL,
    EnderecoIP NVARCHAR(45) NULL,
    Detalhes NVARCHAR(MAX) NULL,
    DataHora DATETIME2 NOT NULL CONSTRAINT DF_LOG_AUDITORIA_DataHora DEFAULT SYSDATETIME(),
    CONSTRAINT PK_LOG_AUDITORIA PRIMARY KEY (LogAuditoria_Id),
    CONSTRAINT FK_LOG_AUDITORIA_USUARIO FOREIGN KEY (Usuario_Id) REFERENCES dbo.USUARIO(Usuario_Id)
);
GO

-- Índices para as consultas mais comuns
