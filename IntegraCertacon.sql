CREATE INDEX IX_NOTA_FISCAL_Usuario_Id ON dbo.NOTA_FISCAL(Usuario_Id);
CREATE INDEX IX_ITEM_NOTA_FISCAL_NotaFiscal_Id ON dbo.ITEM_NOTA_FISCAL(NotaFiscal_Id);
CREATE INDEX IX_LOG_AUDITORIA_Usuario_Id ON dbo.LOG_AUDITORIA(Usuario_Id);
CREATE INDEX IX_LOG_AUDITORIA_DataHora ON dbo.LOG_AUDITORIA(DataHora);
GO

